GLYPH_ROWS, GLYPH_COLS = 7, 5


def rows(bitmap: str) -> list[str]:
    return bitmap.split("|")


def glyph(ch: str) -> list[str]:
    return rows(FONT.get(ch) or FONT.get(ch.upper()) or FONT["□"])


def text_cells(text: str, gap: int = 1) -> tuple[set[tuple[int, int]], int, int]:
    """Lit cells (x, y) of a string, plus its width in columns and the (negative) top offset used by accents."""
    cells: set[tuple[int, int]] = set()
    x, top = 0, 0
    for ch in text.upper() if text else "":
        g = glyph(ch)
        dy = GLYPH_ROWS - len(g)
        top = min(top, dy)
        for y, row in enumerate(g):
            for cx, v in enumerate(row):
                if v == "#":
                    cells.add((x + cx, y + dy))
        x += GLYPH_COLS + gap
    return cells, max(0, x - gap), top


def bitmap_cells(bitmap: str) -> set[tuple[int, int]]:
    return {(x, y) for y, row in enumerate(rows(bitmap)) for x, v in enumerate(row) if v == "#"}
